def main():
    profile = request("/users/" + USER)
    if not isinstance(profile.get("public_repos"), int):
        raise RuntimeError("Missing public repository count")
    def count(query):
        obj = request("/search/issues?" + urlencode({"q": query, "per_page": 1}))
        value = obj.get("total_count")
        if not isinstance(value, int):
            raise RuntimeError("Missing PR search count")
        return value
    merged = count(f"type:pr author:{USER} is:merged")
    opened = count(f"type:pr author:{USER} is:open")
    outputs = {"github-metrics.svg": metric_svg(profile["public_repos"], merged, opened)}
    for info in PULLS:
        pr = request("/repos/" + info["repo"] + "/pulls/" + str(info["number"]))
        author = pr.get("user", {}).get("login", "")
        if author.casefold() != USER.casefold():
            raise RuntimeError("Unexpected PR author for " + info["repo"])
        status = "MERGED" if pr.get("merged_at") else ("OPEN" if pr.get("state") == "open" else "CLOSED")
        outputs[info["file"]] = pr_svg(info, status)
    OUT.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (OUT / name).write_text(content + "\n", encoding="utf-8")
    print(f"Verified public GitHub metrics: repos={profile['public_repos']}, merged={merged}, open={opened}. Cards refreshed.")

if __name__ == "__main__":
    main()
